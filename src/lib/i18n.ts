const tables = { en, id }

export const lang = computed<'en' | 'id'>(() => {
  if (state.settings.lang !== 'auto') return state.settings.lang
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('id') ? 'id' : 'en'
})

export function t(key: Key, params: Record<string, string | number> = {}): string {
  let text: string = tables[lang.value][key] ?? en[key] ?? key
  for (const [name, value] of Object.entries(params)) text = text.replace(`{${name}}`, String(value))
  return text
}

/** For keys built at runtime, e.g. `deck.${id}.name`. */
export const tk = (key: string, params: Record<string, string | number> = {}) => t(key as Key, params)

export const locale = computed(() => (lang.value === 'id' ? 'id-ID' : 'en-US'))
